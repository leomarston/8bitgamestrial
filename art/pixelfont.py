DOT = ["00000","00000","00100","01110","00100","00000","00000"]  # middot via '*'
G["*"] = DOT


def text(s, scale=2, color=(255, 255, 255), spacing=1):
    s = s.upper()
    glyphs = [G.get(c, G[" "]) for c in s]
    w = (5 * len(glyphs) + spacing * (len(glyphs) - 1)) * scale
    h = 7 * scale
    img = Image.new("RGBA", (max(w, 1), h), (0, 0, 0, 0))
    px = img.load()
    cx = 0
    for g in glyphs:
        for ry, row in enumerate(g):
            for rx, bit in enumerate(row):
                if bit == "1":
                    for dy in range(scale):
                        for dx in range(scale):
                            px[cx + rx * scale + dx, ry * scale + dy] = (*color, 255)
        cx += (5 + spacing) * scale
    return img


def text_shadow(s, scale=2, color=(255, 255, 255), shadow=(20, 16, 30), spacing=1):
    """Text with a 1-pixel(*scale) drop shadow for readability."""
    fg = text(s, scale, color, spacing)
    sh = text(s, scale, shadow, spacing)
    out = Image.new("RGBA", (fg.width + scale, fg.height + scale), (0, 0, 0, 0))
    out.alpha_composite(sh, (scale, scale))
    out.alpha_composite(fg, (0, 0))
    return out
